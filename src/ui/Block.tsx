/**
 * Блок страницы, привязанный к участку плёнки.
 *
 * Плёнка идёт фоном всей страницы, а не прологом: её прогресс считается по
 * общей прокрутке. Значит доля высоты, которую занимает блок, — это ровно тот
 * участок сцены, который под ним проходит. Раскадровка (`docs/STORYBOARD.md`)
 * писалась под это: внутри блока камера почти стоит, между блоками — быстрый
 * бросок. Поэтому текст ложится на спокойный кадр, а смена темы совпадает с
 * движением камеры.
 *
 * Маршрут камеры из `render/scene.py`:
 *   0.00–0.20  общий план, пустая чашка
 *   0.20–0.44  сближение, зерно
 *   0.44–0.74  налив
 *   0.74–1.00  взгляд внутрь и финал
 *
 * `screens` каждого блока подобраны так, чтобы их доли совпадали с этими
 * границами — иначе текст про обжарку встанет над наливом.
 *
 * Подложек под текст здесь нет намеренно. Полупрозрачная плашка превращает
 * сцену в картинку за стеклом: кадр перестаёт быть кадром и становится обоями.
 * Текст лежит прямо на сцене, а читаемость держится тенью самих букв.
 */
interface Props {
  children: React.ReactNode
  /** сколько экранов прокрутки занимает блок */
  screens: number
  /** держать содержимое по центру экрана, пока идёт блок */
  hold?: boolean
  className?: string
  id?: string
}

export function Block({ children, screens, hold = true, className = '', id }: Props) {
  return (
    <section id={id} className="relative" style={{ height: `${screens * 100}svh` }}>
      <div className={hold ? `sticky top-0 flex min-h-[100svh] items-center ${className}` : className}>
        {children}
      </div>
    </section>
  )
}
